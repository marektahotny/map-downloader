#!/usr/bin/env python3
"""Embeds addon/Web/index.html into a C++ header (addon/Build/Generated/WebUi.hpp).

The palette loads the UI with DG::Browser::LoadHTML, so the add-on is a single
.apx file without any side files. A byte array is used instead of a string
literal because MSVC limits string literals to ~16 KB.
"""
import os
import sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(root, "addon", "Web", "index.html")
dst_dir = os.path.join(root, "addon", "Build", "Generated")
dst = os.path.join(dst_dir, "WebUi.hpp")

with open(src, "rb") as f:
    data = f.read()

os.makedirs(dst_dir, exist_ok=True)
lines = []
for i in range(0, len(data), 24):
    chunk = data[i:i + 24]
    lines.append("\t" + ",".join(str(b) for b in chunk) + ",")

with open(dst, "w", encoding="ascii", newline="\n") as f:
    f.write("// Generated by tools/embed_html.py - do not edit\n")
    f.write("#ifndef PILON_WEBUI_HPP\n#define PILON_WEBUI_HPP\n\n")
    f.write("static const char kWebUiHtml[] = {\n")
    f.write("\n".join(lines))
    f.write("\n\t0\n};\n\n#endif\n")

print(f"embedded {len(data)} bytes -> {dst}")
sys.exit(0)
